int	valid_tab(int *tab)
{
	int	i;

	i = 0;
	while (i < 4)
	{
		if ((tab[i] + tab[i + 4]) < 3 || (tab[i] + tab[i + 4]) > 5)
			return (0);
		i++;
	}
	i = 8;
	while (i < 12)
	{
		if ((tab[i] + tab[i + 4]) < 3 || (tab[i] + tab[i + 4]) > 5)
			return (0);
		i++;
	}
	return (1);
}
