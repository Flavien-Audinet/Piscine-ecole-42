void	ft_rev_int_tab(int *tab, int size)
{
	int	x;
	int	y;
	int	temp;

	y = -1;
	x = size;
	while (++y <= --x)
	{
		temp = tab[y];
		tab[y] = tab[x];
		tab[x] = temp;
	}
}
